export const ENEMIES_BY_ID: Readonly<Record<number, EnemyInfo>> = Object.fromEntries(
  ENEMIES.map((e) => [e.id, e]),
);

/** Look up an enemy name by its NES enemy ID. Returns undefined for unknown IDs. */
export function getEnemyById(id: number): EnemyInfo | undefined {
  return ENEMIES_BY_ID[id];
}

export function getEnemyNameById(id: number): string | undefined {
  return getEnemyById(id)?.name;
}
